static int mem_range(void *ctx, uint64_t offset, size_t len, uint8_t *dst) {
    const uint8_t *base = (const uint8_t *)ctx;
    if (offset + len > sizeof(ZIP)) return -1;
    memcpy(dst, base + offset, len);
    return 0;
}

static int fails = 0;
#define CHECK(cond, msg) do { \
    if (!(cond)) { printf("FAIL: %s\n", msg); fails++; } \
    else { printf("ok:   %s\n", msg); } \
} while (0)

int main(void) {
    printf("nzip C ABI smoke test (%s), fixture %u bytes\n", nzip_version(), (unsigned)sizeof(ZIP));

    nzip_archive_t *z = nzip_open_remote(mem_range, (void *)ZIP, sizeof(ZIP));
    CHECK(z != NULL, "nzip_open_remote");
    if (!z) return 1;

    CHECK(nzip_entry_count(z) == 3, "entry_count == 3");
    CHECK(nzip_total_size(z) == sizeof(ZIP), "total_size matches fixture");

    /* Metadata cost: tail window + (maybe) central directory. */
    const unsigned long long meta_bytes = nzip_fetched_bytes(z);
    const unsigned meta_calls = nzip_range_calls(z);
    printf("metadata: %llu bytes in %u range calls\n", meta_bytes, meta_calls);
    CHECK(meta_bytes > 0 && meta_calls >= 1, "metadata fetch happened");

    uint64_t usize = 0;
    int idx = nzip_find_entry(z, "hello.txt", &usize);
    CHECK(idx == 0, "find hello.txt index 0");
    CHECK(usize == 11, "hello.txt uncompressed_size == 11");

    uint8_t buf[4096];
    memset(buf, 0, sizeof(buf));
    int n = nzip_extract_entry(z, "hello.txt", buf, sizeof(buf));
    CHECK(n == 11, "extract hello.txt returns 11");
    CHECK(memcmp(buf, "hello nzip\n", 11) == 0, "hello.txt payload matches");

    /* Per-extract cost must stay below the archive size: that is the whole point. */
    const unsigned long long one_extract = nzip_fetched_bytes(z) - meta_bytes;
    printf("first extract added %llu bytes in %u range calls\n",
           one_extract, nzip_range_calls(z) - meta_calls);
    CHECK(one_extract > 0, "extract fetches payload bytes");
    CHECK(one_extract < sizeof(ZIP), "one extract is cheaper than the whole archive");

    uint64_t lsize = 0;
    idx = nzip_find_entry(z, "data/lorem.txt", &lsize);
    CHECK(idx >= 0 && lsize == 1080, "find data/lorem.txt");
    n = nzip_extract_entry(z, "data/lorem.txt", buf, sizeof(buf));
    CHECK(n == 1080, "extract deflate member returns 1080");
    CHECK(memcmp(buf, "lorem ipsum dolor sit amet lorem ipsum", 38) == 0, "deflate payload prefix matches");

    uint64_t bsize = 0;
    idx = nzip_find_entry(z, "data/raw.bin", &bsize);
    CHECK(idx >= 0 && bsize == 2048, "find data/raw.bin");
    n = nzip_extract_entry(z, "data/raw.bin", buf, sizeof(buf));
    CHECK(n == 2048, "extract raw.bin returns 2048");
    CHECK(buf[0] == 0 && buf[255] == 255 && buf[256] == 0, "raw.bin byte pattern");

    nzip_entry_info_t info;
    char name[64];
    CHECK(nzip_entry_at(z, 1, name, sizeof(name), &info) == 0, "entry_at ok");
    CHECK(strcmp(name, "data/lorem.txt") == 0, "entry_at name");
    CHECK(info.method == 8, "entry_at method deflate");
    CHECK(info.uncompressed_size == 1080, "entry_at size");

    CHECK(nzip_find_entry(z, "nope.bin", NULL) == NZIP_ERR_NOT_FOUND, "missing entry -> NOT_FOUND");
    CHECK(nzip_extract_entry(z, "hello.txt", buf, 4) == NZIP_ERR_BUFFER, "small buffer -> ERR_BUFFER");

    uint64_t alen = 0;
    uint8_t *heap = nzip_extract_entry_alloc(z, 0, &alen);
    CHECK(heap != NULL && alen == 11, "extract_entry_alloc");
    CHECK(heap && memcmp(heap, "hello nzip\n", 11) == 0, "alloc payload matches");
    nzip_free(heap, alen);

    printf("range_calls=%u fetched_bytes=%llu total_size=%llu\n",
           nzip_range_calls(z),
           (unsigned long long)nzip_fetched_bytes(z),
           (unsigned long long)nzip_total_size(z));

    nzip_close(z);
    nzip_close(NULL);

    if (fails) { printf("%d FAILURES\n", fails); return 1; }
    printf("all good\n");
    return 0;
}
